/**
 * Imports public, externally hosted meme templates into the static game
 * catalogue. It intentionally stores metadata and remote image URLs only;
 * no third-party images are downloaded into this repository.
 *
 * Source: https://justmeme.wtf/api-docs (free, no API key)
 * Run: npm exec tsx scripts/import-free-meme-templates.ts
 */
import { readFile, writeFile } from "node:fs/promises";

const API = "https://justmeme.wtf/api/v1/templates";
const PAGE_SIZE = 100;
const INDEX_PATH = new URL("../packages/shared/src/index.ts", import.meta.url);
const OUTPUT_PATH = new URL("../packages/shared/src/freeTemplates.ts", import.meta.url);

type RemoteTemplate = {
  id: string;
  name: string;
  slug: string;
  url: string;
  categories?: string[];
};

type ImportedTemplate = {
  id: string;
  name: string;
  url: string;
  source: string;
  categories: string[];
};

function memePartyCategories(categories: string[] = [], name = "") {
  const tags = new Set(categories.map((category) => category.toLowerCase()));
  const mapped = new Set<string>();
  const text = `${name} ${categories.join(" ")}`.toLowerCase();

  if (["animal", "animals"].some((tag) => tags.has(tag))) mapped.add("animals");
  if (["cartoon", "comic"].some((tag) => tags.has(tag))) {
    mapped.add("comics");
  }
  if (["movie", "movies", "tv"].some((tag) => tags.has(tag))) mapped.add("movies");
  if (tags.has("gaming")) mapped.add("gaming");
  if (["school", "college", "education"].some((tag) => tags.has(tag))) mapped.add("school");
  if (["tech", "technology", "coding"].some((tag) => tags.has(tag))) mapped.add("tech");
  if (["sport", "sports"].some((tag) => tags.has(tag))) mapped.add("sports");
  if (tags.has("wholesome")) mapped.add("wholesome");
  if (/\b(game|gaming|gamer|xbox|playstation|pokemon|mario|zelda|minecraft|fortnite)\b/.test(text)) mapped.add("gaming");
  if (/\b(movie|cinema|film|tv|series|star wars|marvel)\b/.test(text)) mapped.add("movies");
  if (/\b(school|teacher|student|college|exam|classroom|study)\b/.test(text)) mapped.add("school");
  if (/\b(computer|coding|code|programmer|developer|software|robot|internet|tech)\b/.test(text)) mapped.add("tech");
  if (/\b(sport|football|soccer|basketball|nba|nfl|ronaldo|messi)\b/.test(text)) mapped.add("sports");
  if (/\b(wholesome|cute|hug|friendship|happy)\b/.test(text)) mapped.add("wholesome");
  if (["workplace", "work", "relatable"].some((tag) => tags.has(tag))) {
    mapped.add("work");
  }
  if (["reaction", "approval", "relationship"].some((tag) => tags.has(tag))) {
    mapped.add("reactions");
  }
  if (["classic", "trending", "comparison", "label", "two-panel", "multi-panel", "four-panel", "expanding"].some((tag) => tags.has(tag))) {
    mapped.add("classic");
  }

  // The public source has incomplete tags for parts of its long-tail archive.
  // Keeping those templates in Classic means every imported entry remains
  // selectable with the default lobby configuration.
  if (mapped.size === 0) mapped.add("classic");
  return [...mapped];
}

async function getPage(page: number) {
  const response = await fetch(`${API}?page=${page}&limit=${PAGE_SIZE}`);
  if (!response.ok) throw new Error(`Template API returned HTTP ${response.status}`);
  const data = (await response.json()) as { success: boolean; templates: RemoteTemplate[] };
  if (!data.success || !Array.isArray(data.templates)) {
    throw new Error("Template API returned an invalid response");
  }
  return data.templates;
}

async function main() {
  const currentIndex = await readFile(INDEX_PATH, "utf8");
  const curatedFiles = new Set(
    [...currentIndex.matchAll(/"([a-zA-Z0-9]+\.(?:jpg|jpeg|png|webp))"/g)].map((match) => match[1]),
  );
  const imported: ImportedTemplate[] = [];
  const seenUrls = new Set<string>();
  for (let page = 1; ; page += 1) {
    const pageTemplates = await getPage(page);
    if (pageTemplates.length === 0) break;

    for (const template of pageTemplates) {
      const filename = new URL(template.url).pathname.split("/").pop() ?? "";
      if (
        !template.name.trim() ||
        !template.slug ||
        !template.url.startsWith("https://i.imgflip.com/") ||
        curatedFiles.has(filename) ||
        seenUrls.has(template.url)
      ) {
        continue;
      }

      seenUrls.add(template.url);
      imported.push({
        id: `justmeme-${template.slug}`,
        name: template.name.trim(),
        url: template.url,
        source: `https://justmeme.wtf/meme/${encodeURIComponent(template.slug)}`,
        categories: memePartyCategories(template.categories, template.name),
      });
    }

    if (pageTemplates.length < PAGE_SIZE) break;
  }

  if (imported.length === 0) throw new Error("No suitable external templates found");

  const source = `// Generated by scripts/import-free-meme-templates.ts on ${new Date().toISOString()}.\n// Source catalogue: https://justmeme.wtf/api-docs\n// Images remain externally hosted; do not edit this file by hand.\nimport type { Category, Template } from "./index.js";\n\nexport const freeTemplates: Template[] = ${JSON.stringify(imported, null, 2)}.map((template) => ({\n  ...template,\n  categories: template.categories as Category[],\n}));\n`;
  await writeFile(OUTPUT_PATH, source, "utf8");
  console.log(
    `Imported ${imported.length} additional external templates; ` +
      `the complete catalogue now has ${imported.length + curatedFiles.size + 3} templates.`,
  );
}

await main();
