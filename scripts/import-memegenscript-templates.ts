/**
 * Imports template metadata from the MIT-licensed Memegenscript repository.
 * Images stay on raw.githubusercontent.com and are not copied into MemeParty.
 * Source: https://github.com/terryds/memegenscript
 */
import { writeFile } from "node:fs/promises";
import { templates, type Category, type Template } from "../packages/shared/src/index.js";
import { freeTemplates } from "../packages/shared/src/freeTemplates.js";

const TREE_URL = "https://api.github.com/repos/terryds/memegenscript/git/trees/main?recursive=1";
const OUTPUT_PATH = new URL("../packages/shared/src/communityTemplates.ts", import.meta.url);

function normalized(value: string) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, "");
}

function title(slug: string) {
  return slug
    .split(/[-_]+/)
    .filter(Boolean)
    .map((word) => word.length <= 3 ? word.toUpperCase() : word[0].toUpperCase() + word.slice(1))
    .join(" ");
}

function categories(slug: string): Category[] {
  const value = slug.toLowerCase();
  const result = new Set<Category>(["classic"]);
  if (/cat|dog|bird|bear|monkey|seal|pigeon|frog|duck|goat|animal/.test(value)) result.add("animals");
  if (/game|gaming|minecraft|zelda|pokemon|mario|sonic|roblox/.test(value)) result.add("gaming");
  if (/school|teacher|student|college|exam|study/.test(value)) result.add("school");
  if (/computer|code|program|tech|robot|ai-|developer|internet/.test(value)) result.add("tech");
  if (/football|soccer|basket|sport|ronaldo|messi|nba|nfl/.test(value)) result.add("sports");
  if (/movie|cinema|star-wars|marvel|batman|spiderman|spongebob|simpson/.test(value)) result.add("movies");
  if (/happy|wholesome|hug|friend|love|cute/.test(value)) result.add("wholesome");
  if (/reaction|surprise|confused|cry|laugh|angry|sad|smile|face/.test(value)) result.add("reactions");
  return [...result];
}

async function main() {
  const response = await fetch(TREE_URL, { headers: { "User-Agent": "MemeParty-Catalog-Importer" } });
  if (!response.ok) throw Error(`GitHub returned HTTP ${response.status}`);
  const data = await response.json() as { tree?: { path: string }[] };
  const known = new Set(
    [...templates, ...freeTemplates].flatMap((template) => [
      normalized(template.id.replace(/^(imgflip|justmeme)-/, "")),
      normalized(template.name),
    ]),
  );
  const imported: Template[] = [];
  for (const item of data.tree ?? []) {
    const match = item.path.match(/^assets\/templates\/([^/]+)\/default\.(png|jpe?g|webp|gif)$/i);
    if (!match) continue;
    const [, slug, extension] = match;
    if (slug.startsWith("_") || known.has(normalized(slug))) continue;
    const name = title(slug);
    if (known.has(normalized(name))) continue;
    known.add(normalized(slug));
    known.add(normalized(name));
    imported.push({
      id: `memegenscript-${slug}`,
      name,
      url: `https://raw.githubusercontent.com/terryds/memegenscript/main/${item.path}`,
      categories: categories(slug),
      source: `https://memegenscript.com/memes/${encodeURIComponent(slug)}`,
    });
  }
  const output = `// Generated by scripts/import-memegenscript-templates.ts on ${new Date().toISOString()}.\n// Metadata only; images remain externally hosted by the source repository.\nimport type { Template } from "./index.js";\n\nexport const communityTemplates: Template[] = ${JSON.stringify(imported, null, 2)};\n`;
  await writeFile(OUTPUT_PATH, output, "utf8");
  console.log(`Imported ${imported.length} additional Memegenscript templates.`);
}

await main();
